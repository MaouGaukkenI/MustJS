/**
 * Gets a readable identifier for a recipe ingredient or output.
 *
 * @param {Object|null|undefined} object - The ingredient or output object.
 * @returns {string} The item, tag, fluid, or an indication of invalid data.
 */
function mustjsGetObjectIdAE2(object) {
    if (object === null || object === undefined) {
        return "undefined";
    }

    if (typeof object !== "object") {
        return String(object);
    }

    if (typeof object.item === "string") {
        return object.item;
    }

    if (typeof object.tag === "string") {
        return `#${object.tag}`;
    }

    if (typeof object.fluid === "string") {
        return object.fluid;
    }

    if (typeof object.id === "string") {
        return object.id;
    }

    if (object.stack && typeof object.stack.id === "string") {
        return object.stack.id;
    }

    return "unknown";
}

// === Recipe generation helper functions ===
/**
 * Creates an AE2 Inscriber recipe.
 *
 * @param {Object} e - The recipe event object.
 * @param {Object} output - The recipe output item.
 *                          Use the helper function `itemOutput()` or `itemOutputStack()`.
 * @param {Array<Object>} input - Array containing the bottom, middle, and top ingredients.
 *                          Use helper functions such as `itemInput()` or `itemInputTag()`.
 *                          All items must be wrapped inside an array [].
 * @param {string} mode - The Inscriber recipe mode (e.g., "inscribe", "press").
 *
 * @example
 *  inscriberPress(
 *      e,
 *      itemOutput("ae2:printed_silicon"),
 *      [
 *          itemInput("ae2:silicon"),
 *          itemInput("minecraft:iron_ingot"),
 *          itemInput("ae2:silicon")
 *      ],
 *      "inscribe"
 *  )
 *
 *  @remarks
 * - Creates an AE2 Inscriber recipe using the specified bottom, middle, and top ingredients.
 */
function inscriberPress(e, output, input, mode) {
    const recipeType = "inscriber_press";
    const diagnosticId = mustjsDiagnosticRecipeIdAE2(recipeType, output);
    const validMode = ["inscribe", "press"]

    let error = false;

    // Validate Mode
    if (!validMode.includes(mode)) {
        console.error(
            `[MustJS] [${diagnosticId}] Inscriber: Invalid mode.\n` +
            `Valid modes: "inscribe" or "press".\n` +
            `Input mode: ${mode}`
        );

        error = true;
    }

    // Validate Output
    if(!validateOutputAE2(output)){
        console.error(
            `[MustJS] [${diagnosticId}] Inscriber: Invalid output. \n` +
            `Item Output: ${mustjsGetObjectIdAE2(output)}\n`+
            "Expected a valid item output created with an item output helper."
        )

        error = true;
    }

    // Validate Inputs
    if (!Array.isArray(input) || input.length === 0) {
        console.error(
            `[MustJS] [${diagnosticId}] Inscriber: Invalid inputs.\n` +
            "Expected a non-empty array of item, item tag, or fluid inputs."
        );

        error = true;
    } else if (input.length !== 3) {
        console.error(
            `[MustJS] [${diagnosticId}] Inscriber: Invalid inputs.\n` +
            "Expected an array containing exactly 3 item, item tag, or fluid inputs."
        );

        error = true;
    } else {
        for (let i = 0; i < input.length; i++) {
            if (!validateInputAE2(input[i])) {
                console.error(
                    `[MustJS] [${diagnosticId}] Inscriber: Invalid input at index ${i}.\n` +
                    `Item Input ${i}: ${mustjsGetObjectIdAE2(input[i])}\n` +
                    "Expected a valid item, item tag, or fluid input."
                );

                error = true;
            }
        }
    }



    if(error){
        return
    }

    const recipeBase = `mustjs:${recipeType}/${output.id.replace(":", "_")}`;
    const recipeId = mustjsUniqueRecipeIdAE2(recipeBase);

    e.custom({
        "type": "ae2:inscriber",
        "ingredients": {
            "bottom": input[0],
            "middle": input[1],
            "top": input[2]
        },
        "mode": mode,
        "result": output
    }).id(recipeId);
}

/**
 * Creates an AE2 transformation recipe.
 *
 * @param {Object} e - The recipe event object.
 * @param {Object} output - The recipe output item.
 *                          Use the helper function `itemOutput()` or `itemOutputStack()`.
 * @param {Array<Object>} input - Array containing the recipe input ingredients.
 *                          The first input must be 'ae2:charged_certus_quartz_crystal'.
 *                          Use helper functions such as `itemInput()` or `itemInputTag()`.
 *                          All items must be wrapped inside an array [].
 *
 * @example
 *  transform(
 *      e,
 *      itemOutput("ae2:fluix_crystal"),
 *      [
 *          itemInput("ae2:charged_certus_quartz_crystal"),
 *          itemInput("minecraft:redstone"),
 *          itemInput("minecraft:quartz")
 *      ]
 *  )
 *
 *  @remarks
 * - Transforms the specified ingredients into the output item.
 */
function transform(e, output, input) {
    const recipeType = "transform";
    const diagnosticId = mustjsDiagnosticRecipeIdAE2(recipeType, output);
    let error = false;

    // Validate Output
    if(!validateOutputAE2(output)){
        console.error(
            `[MustJS] [${diagnosticId}] Transform: Invalid output. \n` +
            `Item Output: ${mustjsGetObjectIdAE2(output)}\n`+
            "Expected a valid item output created with an item output helper."
        )

        error = true;
    }

    // Force charged_certus_quartz_crystal as input[0]
    const input0 = "ae2:charged_certus_quartz_crystal";

    let input0Index = -1;

    for (let i = 0; i < input.length; i++) {
        if (input[i] && input[i].item === input0) {
            input0Index = i;
            break;
        }
    }

    if (input0Index > 0) {
        let chargedCertusQuartz = input.splice(input0Index, 1)[0];
        input.unshift(chargedCertusQuartz);

        console.warn(
            `[MustJS] [${diagnosticId}] Transform: Warning.\n` +
            `The required input '${input0}' was found at index ${input0Index}.\n` +
            "It was automatically moved to index 0."
        );
    } else if (input0Index === -1) {
        input.unshift({ item: input0 });

        console.warn(
            `[MustJS] [${diagnosticId}] Transform: Warning.\n` +
            `The required input '${input0}' was missing.\n` +
            "It was automatically added at index 0."
        );
    }

    //Validate Inputs
    if (!Array.isArray(input) || input.length === 0) {
        console.error(
            `[MustJS] [${diagnosticId}] Transform: Invalid inputs.\n` +
            "Expected a non-empty array of item, item tag, or fluid inputs."
        );

        error = true;
    } else {
        for (let i = 0; i < input.length; i++) {
            if (!validateInputAE2(input[i])) {
                console.error(
                    `[MustJS] [${diagnosticId}] Transform: Invalid input at index ${i}.\n` +
                    `Item Input ${i}: ${mustjsGetObjectIdAE2(input[i])}\n` +
                    "Expected a valid item, item tag, or fluid input."
                )

                error = true;
            }
        }
    }

    if (error){
        return;
    }

    const recipeBase = `mustjs:${recipeType}/${output.id.replace(":", "_")}`;
    const recipeId = mustjsUniqueRecipeIdAE2(recipeBase);

    e.custom({
        "type": "ae2:transform",
        "ingredients": input,
        "result": output
    }).id(recipeId);
}

/**
 * Creates an AE2 Charger recipe.
 *
 * @param {Object} e - The recipe event object.
 * @param {Object} output - The recipe output item.
 *                          Use the helper function `itemOutput()` or `itemOutputStack()`.
 * @param {Object} input - The recipe input ingredient.
 *                          Use helper functions such as `itemInput()` or `itemInputTag()`.
 *
 * @example
 *  charger(
 *      e,
 *      itemOutput("ae2:charged_certus_quartz_crystal"),
 *      itemInput("ae2:certus_quartz_crystal")
 *  )
 *
 *  @remarks
 * - Charges the specified input item and produces the output item.
 */
function charger(e, output, input) {
    const recipeType = "charger";
    const diagnosticId = mustjsDiagnosticRecipeIdAE2(recipeType, output);
    let error = false;

    // Validate Output
    if(!validateOutputAE2(output)){
        console.error(
            `[MustJS] [${diagnosticId}] Transform: Invalid output. \n` +
            `Item Output: ${mustjsGetObjectIdAE2(output)}\n`+
            "Expected a valid item output created with an item output helper."
        )

        error = true;
    }

    // Validate Input
    if(!validateInputAE2(input)){
        console.error(
            `[MustJS] [${diagnosticId}] Transform: Invalid input. \n` +
            `Item Input: ${mustjsGetObjectIdAE2(input)}\n`+
            "Expected a valid item output created with an item output helper."
        )

        error = true;
    }

    if(error){
        return
    }

    const recipeBase = `mustjs:${recipeType}/${output.id.replace(":", "_")}`;
    const recipeId = mustjsUniqueRecipeIdAE2(recipeBase);
    e.custom({
        "type": "ae2:charger",
        "ingredient": input,
        "result": output
    }).id(recipeId);
}
