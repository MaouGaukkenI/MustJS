/**
 * Creates a custom mixing recipe using the Create mod.
 *
 * @param e - Recipe creation event, for example, `ServerEvents.recipes(event => {})`, pass in `event`
 *
 * @param {Array|Object} output - The resulting items or blocks from the recipe, more than one item can be used.
 *                                Use helper functions like `itemOutput()`, `itemOutputStack()`, `itemOutpuChance()` or `itemOutputChanceStack()`.
 *                                All items must be wrapped inside an array [].
 * @param {Array<Object>} input - The list of ingredient items required for the recipe, more than one item can be generated.
 *                                Use helper functions such as `itemInput()`, `itemInputTag()` or `fluidInput()`.
 *                                All items must be wrapped inside an array [].
 * @param {boolean|string} heat - The heat requirement for the recipe.
 *                                Allowed values: false, "heated", "superheated".
 *
 * @returns {void} - This function does not return a value; it registers the recipe.
 *
 * @example:
 * mixing(
 *   e,
 *   [itemOutputStack("minecraft:cookie", 8)],
 *   [
 *     itemInput("minecraft:wheat"),
 *     itemInput("minecraft:cocoa_beans")
 *   ],
 *   "heated"
 * );
 *
 * @remarks:
 * - If `heat` is false, the recipe will not require heat.
 * - If `heat` is "heated" or "superheated", the recipe will include a heat requirement.
 * - Invalid values for `heat` will trigger an error message in the console.
 */
function mixing(e, output, input, heat) {
    const recipeType = "mixing";
    const states = [false, "heated", "superheated"];
    let error = false;

    const results = Array.isArray(output) ? output : [output];

    if (results.length === 0) {
        const diagnosticId = mustjsDiagnosticRecipeIdCBF(recipeType, null);

        console.error(
            `[MustJS] [${diagnosticId}] Mixing: Invalid output. ` +
            "Expected a non-empty array of valid item or fluid outputs."
        );
        error = true;
    }

    // Validate and normalize outputs.
    const normalizedResults = [];

    for (let i = 0; i < results.length; i++) {
        const result = results[i];

        if (!validateOutputCBF(result)) {
            const diagnosticId = mustjsDiagnosticRecipeIdCBF(
                recipeType,
                result
            );

            console.error(
                `[MustJS] [${diagnosticId}] Mixing: Invalid output at index ${i}. ` +
                "Expected a valid item or fluid output."
            );
            error = true;
        }

        if (Object.prototype.hasOwnProperty.call(result, "amount")) {
            // Fluid output: { id, amount }
            normalizedResults.push({
                id: result.id,
                amount: result.amount
            });
        } else {
            // Item output: { id, count?, chance? }
            const normalizedResult = {
                id: result.id
            };

            if (result.count !== undefined) {
                if (
                    !Number.isSafeInteger(result.count) ||
                    result.count <= 0
                ) {
                    const diagnosticId = mustjsDiagnosticRecipeIdCBF(
                        recipeType,
                        result
                    );

                    console.error(
                        `[MustJS] [${diagnosticId}] Mixing: Invalid output count ` +
                        `at index ${i}. Expected a positive safe integer.`
                    );
                    error = true;
                }

                normalizedResult.count = result.count;
            }

            if (result.chance !== undefined) {
                if (
                    typeof result.chance !== "number" ||
                    !Number.isFinite(result.chance) ||
                    result.chance < 0 ||
                    result.chance > 1
                ) {
                    const diagnosticId = mustjsDiagnosticRecipeIdCBF(
                        recipeType,
                        result
                    );

                    console.error(
                        `[MustJS] [${diagnosticId}] Mixing: Invalid output chance ` +
                        `at index ${i}. Expected a number between 0 and 1.`
                    );
                    error = true;
                }

                normalizedResult.chance = result.chance;
            }

            normalizedResults.push(normalizedResult);
        }
    }

    // Validate inputs.
    if (!Array.isArray(input) || input.length === 0) {
        const diagnosticId = mustjsDiagnosticRecipeIdCBF(
            recipeType,
            results[0]
        );

        console.error(
            `[MustJS] [${diagnosticId}] Mixing: Invalid inputs. ` +
            "Expected a non-empty array of item, item tag, or fluid inputs."
        );
        error = true;
    }

    for (let i = 0; i < input.length; i++) {
        if (!validateInputCBF(input[i])) {
            const diagnosticId = mustjsDiagnosticRecipeIdCBF(
                recipeType,
                results[0]
            );

            console.error(
                `[MustJS] [${diagnosticId}] Mixing: Invalid input at index ${i}. ` +
                "Expected a valid item, item tag, or fluid input."
            );
            error = true;
        }
    }

    // Validate heat requirement.
    if (!states.includes(heat)) {
        const diagnosticId = mustjsDiagnosticRecipeIdCBF(
            recipeType,
            results[0]
        );

        console.error(
            `[MustJS] [${diagnosticId}] Mixing: Invalid heat requirement '${heat}'. ` +
            'Allowed values are false, "heated", or "superheated".'
        );
        error = true;
    }

    if(error){return}

    // Build recipe.
    const recipe = {
        type: "create:mixing",
        ingredients: input,
        results: normalizedResults
    };

    if (heat !== false) {
        recipe.heat_requirement = heat;
    }

    const recipeBase =
        `mustjs:${recipeType}/${results[0].id.replace(":", "_")}`;

    const recipeId = mustjsUniqueRecipeIdCBF(recipeBase);

    e.custom(recipe).id(recipeId);
}

