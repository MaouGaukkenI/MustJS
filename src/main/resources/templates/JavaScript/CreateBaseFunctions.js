/**
 * Creates a custom compacting recipe using the Create mod.
 *
 * @param e - Recipe creation event, for example, `ServerEvents.recipes(event => {})`, pass in `event`
 *
 * @param {Object} output - The resulting item or block from the recipem, only one item can be generated.
 *                          Use the helper function `itemOutput()` or `itemOutputStack()`.
 * @param {Array} inputs - The list of ingredient items required for the recipe, more than one item can be used.
 *                          Use helper functions such as `itemInput()`, `itemInputTag()`, or `fluidInput()`.
 *                          All items must be wrapped inside an array [].
 * @param {boolean|string} heat - The heat requirement for the recipe.
 *                                Allowed values: false, "heated", "superheated".
 *
 * @returns {void} - This function does not return a value; it registers the recipe.
 *
 * @example:
 * compacting(
 *   e,
 *   itemOutput("minecraft:iron_ingot"),
 *   [
 *      itemInput("minecraft:iron_nugget"),
 *      itemInput("minecraft:iron_nugget"),
 *      itemInput("minecraft:iron_nugget"),
 *      itemInput("minecraft:iron_nugget"),
 *      itemInput("minecraft:iron_nugget"),
 *      itemInput("minecraft:iron_nugget"),
 *      itemInput("minecraft:iron_nugget"),
 *      itemInput("minecraft:iron_nugget"),
 *      itemInput("minecraft:iron_nugget")
 *       ],
 *   "heated"
 * )
 *
 * @remarks:
 * - If `heat` is false, the recipe will not require heat.
 * - If `heat` is "heated" or "superheated", the recipe will include a heat requirement.
 * - Invalid values for `heat` will trigger an error message in the console.
 */
function compacting(e, output, inputs, heat) {
    const recipeType = "compacting";
    const states = [false, "heated", "superheated"];
    let error = false

    if (!validateOutputCBF(output)) {
        const diagnosticId = mustjsDiagnosticRecipeIdCBF(recipeType, output);

        console.error(
            `[MustJS] [${diagnosticId}] Compacting: Invalid output. ` +
            "Expected a valid item output created with an item output helper."
        );
        error = true;
    }

    if (!Array.isArray(inputs) || inputs.length === 0) {
        const diagnosticId = mustjsDiagnosticRecipeIdCBF(recipeType, output);

        console.error(
            `[MustJS] [${diagnosticId}] Compacting: Invalid inputs. ` +
            "Expected a non-empty array of item, item tag, or fluid inputs."
        );
        error = true;
    } else {
        for (let i = 0; i < inputs.length; i++) {
            if (!validateInputCBF(inputs[i])) {
                const diagnosticId = mustjsDiagnosticRecipeIdCBF(recipeType, output);

                console.error(
                    `[MustJS] [${diagnosticId}] Compacting: Invalid input at index ${i}. ` +
                    "Expected a valid item, item tag, or fluid input."
                );
                error = true;
            }
        }
    }

    if (!states.includes(heat)) {
        const diagnosticId = mustjsDiagnosticRecipeIdCBF(recipeType, output);

        console.error(
            `[MustJS] [${diagnosticId}] Compacting: Invalid heat requirement '${heat}'. ` +
            'Allowed values are false, "heated", or "superheated".'
        );
        error = true;
    }

    if(error){return}

    const recipe = {
        type: "create:compacting",
        ingredients: inputs,
        results: [output]
    };

    if (heat !== false) {
        recipe.heat_requirement = heat;
    }

    const recipeBase = `mustjs:compacting/${output.id.replace(":", "_")}`;
    const recipeId = mustjsUniqueRecipeIdCBF(recipeBase);

    e.custom(recipe).id(recipeId);
}

/**
 * Creates a custom crushing recipe using the Create mod.
 *
 * @param e - Recipe creation event, for example, `ServerEvents.recipes(event => {})`, pass in `event`
 *
 * @param {Array} output - The resulting items or blocks from the recipe, more than one item can be generated.
 *                         Use helper functions like `itemOutput()`, `itemOutputStack()`, `itemOutpuChance()` or `itemOutputChanceStack()`.
 *                         All items must be wrapped inside an array [].
 * @param {Object} input - The ingredient item required for the recipe, only one item can be used.
 *                         Use helper functions such as `itemInput()` or `itemInputTag()`.
 * @param {number} time - The processing time (in ticks) for the recipe.
 *
 * @returns {void} - This function does not return a value; it registers the recipe.
 *
 * @example:
 * crushing(
 *   e,
 *   [
 *      itemOutput("minecraft:gravel"),
 *      itemOutputChance("minecraft:gravel", 0.25)
 *   ],
 *   itemInput("minecraft:cobblestone"),
 *   200
 * )
 */
function crushing(e, output, input, time) {
    const recipeType = "crushing";
    let error = false;

    if (!Array.isArray(output) || output.length === 0) {
        const diagnosticId = mustjsDiagnosticRecipeIdCBF(recipeType, output);

        console.error(
            `[MustJS] [${diagnosticId}] Crushing: Invalid output. ` +
            "Expected a non-empty array of valid item outputs."
        );
        error = true;
    }

    for (let i = 0; i < output.length; i++) {
        if (!validateOutputCBF(output[i]) ||
            Object.prototype.hasOwnProperty.call(output[i], "amount")) {
            const diagnosticId = mustjsDiagnosticRecipeIdCBF(recipeType, output[i]);

            console.error(
                `[MustJS] [${diagnosticId}] Crushing: Invalid output at index ${i}. ` +
                "Expected a valid item output created with an item output helper."
            );
            error = true;
        }
    }

    if (!validateInputCBF(input) || typeof input.fluid === "string") {
        const diagnosticId = mustjsDiagnosticRecipeIdCBF(recipeType, output[0]);

        console.error(
            `[MustJS] [${diagnosticId}] Crushing: Invalid input. ` +
            "Expected a valid item or item tag input created with itemInput() or itemInputTag()."
        );
        error = true;
    }

    if (typeof time !== "number" || !Number.isFinite(time) || time <= 0) {
        const diagnosticId = mustjsDiagnosticRecipeIdCBF(recipeType, output[0]);

        console.error(
            `[MustJS] [${diagnosticId}] Crushing: Invalid processing time '${time}'. ` +
            "Expected a positive, finite number of ticks."
        );
        error = true;
    }

    if(error){return}

    const recipe = {
        type: "create:crushing",
        ingredients: [input],
        processing_time: time,
        results: output
    };

    const recipeBase = `mustjs:crushing/${output[0].id.replace(":", "_")}`;
    const recipeId = mustjsUniqueRecipeIdCBF(recipeBase);

    e.custom(recipe).id(recipeId);
}

