/**
 * Creates a custom mechanical crafting recipe using the Create mod.
 *
 * @param e - Recipe creation event, for example, `ServerEvents.recipes(event => {})`, pass in `event`
 *
 * @param {Object} output - The resulting item or block from the recipe.
 *                          Use the helper function `itemOutput()` or `itemOutputStack()`.
 * @param {Object} input - The key mapping of characters in the pattern to ingredients.
 *                         Each key should be wrapped in helper functions such as `itemInputKey()` or `itemInputTagKey()`.
 * @param {Array<string>} pattern - The crafting grid pattern represented as an array of strings.
 *                                  Each character corresponds to a key defined in `input`.
 *
 * @returns {void} - This function does not return a value; it registers the recipe.
 *
 * @example:
 * mechanical_crafting(
 *   e,
 *   itemOutputStack("minecraft:diamond_pickaxe", 1),
 *   Object.assign(
 *     {},
 *     itemInputKey("A", "minecraft:diamond"),
 *     itemInputTagKey("B", "c:rods/wooden")
 *   ),
 *   [
 *     "AAA",
 *     " B ",
 *     " B "
 *   ]
 * )
 * @remarks:
 * - If the output is a tool, the quantity must be 1. if it is an item or a block, it can be more.
 */
function mechanical_crafting(e, output, input, pattern) {
    const recipeType = "mechanical_crafting";
    const diagnosticId = mustjsDiagnosticRecipeIdCBF(recipeType, output);
    let error = false;

    if (!validateOutputCBF(output)) {
        console.error(
            `[MustJS] [${diagnosticId}] Mechanical_crafting: Invalid output. ` +
            "Expected a valid item output created with an item output helper."
        );
        error = true;
    }

    if (output.count == null) {
        output.count = 1;
    }

    if (
        !Number.isSafeInteger(output.count) ||
        output.count <= 0
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Mechanical_crafting: Invalid output count. ` +
            "Expected a positive safe integer."
        );
        error = true;
    }

    if (
        typeof input !== "object" ||
        input === null ||
        Array.isArray(input) ||
        Object.keys(input).length === 0
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Mechanical_crafting: Invalid input mapping. ` +
            "Expected a non-empty object created with itemInputKey() or itemInputTagKey()."
        );
        error = true;
    }

    const inputKeys = Object.keys(input);

    for (var i = 0; i < inputKeys.length; i++) {
        var inputKey = inputKeys[i];
        var inputValue = input[inputKey];

        if (
            typeof inputValue !== "object" ||
            inputValue === null ||
            Array.isArray(inputValue) ||
            (
                !Object.prototype.hasOwnProperty.call(inputValue, "item") &&
                !Object.prototype.hasOwnProperty.call(inputValue, "tag")
            )
        ) {
            console.error(
                `[MustJS] [${diagnosticId}] Mechanical_crafting: Invalid input mapping ` +
                `for symbol '${inputKey}'. Expected an item or item tag input.`
            );
            error = true;
        }

        if (
            !validateInputCBF(inputValue) ||
            typeof inputValue.fluid === "string"
        ) {
            console.error(
                `[MustJS] [${diagnosticId}] Mechanical_crafting: Invalid input mapping ` +
                `for symbol '${inputKey}'. The item or item tag does not exist or is invalid.`
            );
            error = true;
        }
    }

    if (
        !Array.isArray(pattern) ||
        pattern.length === 0
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Mechanical_crafting: Invalid pattern. ` +
            "Expected a non-empty array of strings."
        );
        error = true;
    }

    if (
        !pattern.every(row => typeof row === "string" && row.length > 0)
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Mechanical_crafting: Invalid pattern. ` +
            "Each row must be a non-empty string."
        );
        error = true;
    }

    const symbolsInPattern = new Set(pattern.join("").replace(/\s/g, ""));

    for (const symbol of symbolsInPattern) {
        if (!Object.prototype.hasOwnProperty.call(input, symbol)) {
            console.error(
                `[MustJS] [${diagnosticId}] Mechanical_crafting: Invalid pattern. ` +
                `Symbol '${symbol}' is not defined in the input mapping.`
            );
            error = true;
        }
    }

    if(error){return}

    const recipe = {
        type: "create:mechanical_crafting",
        accept_mirrored: false,
        category: "misc",
        key: input,
        pattern: pattern,
        result: output,
        show_notification: false
    };

    const recipeBase =
        `mustjs:mechanical_crafting/${output.id.replace(":", "_")}`;

    const recipeId = mustjsUniqueRecipeIdCBF(recipeBase);

    e.custom(recipe).id(recipeId);
}

