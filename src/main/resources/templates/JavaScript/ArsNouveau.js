/**
 * Creates a recipe for the Ars Nouveau Enchanting Apparatus.
 *
 * Allows you to configure the recipe result, pedestal ingredients,
 * main reagent, Source cost, and whether the reagent's NBT data
 * should be preserved.
 *
 * @param {Object} e The KubeJS recipe event.
 * @param {Object} output The resulting item.
 *                          Use the helper function `itemOutput()` or `itemOutputStack()`.
 * @param {Array<Object>} input An array of ingredients used on the pedestals.
 *                          Use helper functions such as `itemInput()` or `itemInputTag()`.
 *                          All items must be wrapped inside an array [].
 * @param {Object|Array<Object>} reagent The main reagent required by the recipe.
 *                          Use helper functions such as `itemInput()` or `itemInputTag()`.
 * @param {number} sourceCost The amount of Source consumed by the recipe.
 * @param {boolean} KeepNBT Whether the reagent's NBT data should be preserved.
 *
 * @example
 * enchanting_apparatus(
 *     e,
 *     itemOutput('createmechanisms:source_mechanism'),
 *     [
 *         itemInputTag('minecraft:logs'),
 *         itemInputTag('minecraft:logs')
 *     ],
 *     itemInputTag('c:gems/amethyst'),
 *     100,
 *     false
 * );
 */
function enchanting_apparatus(e, output, input, reagent, sourceCost, KeepNBT) {
    const recipeType = "enchanting_apparatus";
    const diagnosticId = mustjsDiagnosticRecipeIdArsN(recipeType, output);
    let error = false;

    // Validate output
    if (!validateOutputArsN(output)) {
        console.error(
            `[MustJS] [${diagnosticId}] Enchanting Apparatus: Invalid output. \n` +
            `Item Output: ${mustjsGetObjectIdArsN(output)}\n`+
            "Expected a valid item output created with an item output helper."
        );
        error = true;
    }

    // Validate inputs
    if (!Array.isArray(input) || input.length === 0) {
        console.error(
            `[MustJS] [${diagnosticId}] Enchanting Apparatus: Invalid inputs. \n` +
            "Expected a non-empty array of item, item tag, or fluid inputs."
        );
        error = true;
    } else {
        for (let i = 0; i < input.length; i++) {
            if (!validateInputArsN(input[i])) {
                console.error(
                    `[MustJS] [${diagnosticId}] Enchanting Apparatus: Invalid input at index ${i}. \n` +
                    `Item Input ${i}: ${mustjsGetObjectIdArsN(input[i])}\n`+
                    "Expected a valid item, item tag, or fluid input."
                );
                error = true;
            }
        }
    }

    // Validate reagent
    if (!validateInputArsN(reagent)) {
        console.error(
            `[MustJS] [${diagnosticId}] Enchanting Apparatus: Invalid reagent. \n` +
            `Item Reagent: ${mustjsGetObjectIdArsN(reagent)}\n`+
            "Expected a valid item, item tag, or fluid input."
        );
        error = true;
    }

    // Validate source cost
    if (
        typeof sourceCost !== "number" ||
        !Number.isFinite(sourceCost) ||
        sourceCost <= 0
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Enchanting Apparatus: Invalid sourceCost. \n` +
            "Expected a positive, finite source cost."
        );
        error = true;
    }

    // Validate KeepNBT
    if (KeepNBT !== true && KeepNBT !== false) {
        console.error(
            `[MustJS] [${diagnosticId}] Enchanting Apparatus: Invalid KeepNBT. \n` +
            "Expected a boolean value (true or false)."
        );
        error = true;
    }

    if (error) {
        return;
    }

    const recipeBase =
        `mustjs:${recipeType}/${output.id.replace(":", "_")}`;

    const recipeId = mustjsUniqueRecipeIdArsN(recipeBase);

    e.custom({
        type: "ars_nouveau:enchanting_apparatus",
        keepNbtOfReagent: KeepNBT,
        result: output,
        pedestalItems: input,
        reagent: reagent,
        sourceCost: sourceCost
    }).id(recipeId);
}

/**
 * Creates a recipe for the Ars Nouveau Imbuement Chamber.
 *
 * Defines the main input ingredient, additional pedestal ingredients,
 * resulting item, and Source cost.
 *
 * The pedestal ingredient array can be empty if the recipe does not
 * require any additional pedestal ingredients.
 *
 * @param {Object} e The KubeJS recipe event.
 * @param {Object} output The item produced by the recipe.
 *                          Use the helper function `itemOutput()` or `itemOutputStack()`.
 * @param {Object} input The main input ingredient.
 *                          Use helper functions such as `itemInput()` or `itemInputTag()`.
 * @param {Array<Object>} pedestalItems An array of additional pedestal ingredients.
 *                          Use helper functions such as `itemInput()` or `itemInputTag()`.
 *                          All items must be wrapped inside an array [].
 * @param {number} sourceCost The amount of Source consumed by the recipe.
 *
 * @example
 * // Recipe without additional pedestal ingredients.
 * imbuement(
 *     e,
 *     itemOutput('createmechanisms:source_mechanism'),
 *     itemInputTag('minecraft:logs'),
 *     [],
 *     2000
 * );
 *
 * @example
 * // Recipe with an additional pedestal ingredient.
 * imbuement(
 *     e,
 *     itemOutput('createmechanisms:source_mechanism'),
 *     itemInputTag('minecraft:logs'),
 *     [
 *         itemInputTag('c:gems/amethyst')
 *     ],
 *     20
 * );
 */
function imbuement(e, output, input, pedestalItems, sourceCost) {
    const recipeType = "imbuement";
    const diagnosticId = mustjsDiagnosticRecipeIdArsN(recipeType, output);
    let error = false;

    // Validate output
    if (!validateOutputArsN(output)) {
        console.error(
            `[MustJS] [${diagnosticId}] Imbuement: Invalid output. \n` +
            `Item Output: ${mustjsGetObjectIdArsN(output)}\n`+
            "Expected a valid item output created with an item output helper."
        );
        error = true;
    }

    // Validate input
    if (!validateInputArsN(input) || typeof input.fluid === "string") {
        console.error(
            `[MustJS] [${diagnosticId}] Imbuement: Invalid input. \n` +
            `Item Input: ${mustjsGetObjectIdArsN(input)}\n`+
            "Expected a valid item input or item tag."
        );
        error = true;
    }

    // Validate pedestal items
    if (!Array.isArray(pedestalItems)) {
        console.error(
            `[MustJS] [${diagnosticId}] Imbuement: Invalid pedestalItems. \n` +
            "Expected a array of valid item or item tag, or an empty array."
        );
        error = true;
    } else {
        for (let i = 0; i < pedestalItems.length; i++) {
            if (
                !validateInputArsN(pedestalItems[i]) ||
                typeof pedestalItems[i].fluid === "string"
            ) {
                console.error(
                    `[MustJS] [${diagnosticId}] Imbuement: Invalid pedestal item at index ${i}. \n` +
                    `Item Input Pedestal ${i}: ${mustjsGetObjectIdArsN(pedestalItems[i])}\n`+
                    "Expected a valid item or item tag input."
                );
                error = true;
            }
        }
    }

    // Validate source cost
    if (
        typeof sourceCost !== "number" ||
        !Number.isFinite(sourceCost) ||
        sourceCost <= 0
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Imbuement: Invalid sourceCost. \n` +
            "Expected a positive, finite source cost."
        );
        error = true;
    }

    if (error) {
        return;
    }

    const recipeBase =
        `mustjs:${recipeType}/${output.id.replace(":", "_")}`;

    const recipeId = mustjsUniqueRecipeIdArsN(recipeBase);

    e.custom({
        type: "ars_nouveau:imbuement",
        count: 1,
        input: input,
        output: output,
        pedestalItems: pedestalItems,
        source: sourceCost
    }).id(recipeId);
}

/**
 * Creates a budding block conversion recipe for Ars Nouveau.
 *
 * Defines the input block and the resulting budding block.
 * The specified input and result must be compatible with the
 * Ars Nouveau budding conversion recipe type.
 *
 * @param {Object} e The KubeJS recipe event.
 * @param {string} output The resulting block or recipe result.
 * @param {string} input The input block or ingredient.
 *
 * @example
 * budding_conversion(
 *     e,
 *     'ae2:flawless_budding_quartz',
 *     'ae2:quartz_block'
 * );
 */
function budding_conversion(e, output, input) {
    const recipeType = "budding_conversion";
    const diagnosticId = mustjsDiagnosticRecipeIdArsN(recipeType, {id: output});
    let error = false;

    // Validate output
    if (!validateOutputArsN({id: output})) {
        console.error(
            `[MustJS] [${diagnosticId}] Budding Conversion: Invalid output. \n` +
            `Item Output: ${mustjsGetObjectIdArsN(output)}\n`+
            "Expected a valid item output created with an item output helper."
        );
        error = true;
    }

    // Validate input
    if (
        !validateInputArsN({item: output}) ||
        typeof input.fluid === "string"
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Budding Conversion: Invalid input. \n` +
            `Item Input: ${mustjsGetObjectIdArsN(input)}\n`+
            "Expected a valid item input or item tag."
        );
        error = true;
    }

    if (error) {
        return;
    }

    let outputId = {id: output}

    const recipeBase =
        `mustjs:${recipeType}/${outputId.id.replace(":", "_")}`;

    const recipeId = mustjsUniqueRecipeIdArsN(recipeBase);

    e.custom({
        type: "ars_nouveau:budding_conversion",
        input: input,
        result: output
    }).id(recipeId);
}

/**
 * Creates a recipe for the Ars Nouveau Scry Ritual.
 *
 * Uses the specified tag for both the ritual's augment and highlight.
 * This allows the ritual to identify and highlight blocks associated
 * with the given tag.
 *
 * @param {Object} e The KubeJS recipe event.
 * @param {string} oreTag The resource location of the tag used by the ritual.
 *
 * @example
 * scry_ritual(e, 'c:ores/aluminum');
 */
function scry_ritual(e, oreTag) {
    const recipeType = "scry_ritual";
    const diagnosticId = `mustjs:${recipeType}/${typeof oreTag === "string" && oreTag.trim() !== "" ? oreTag.replace(":", "_") : "unknown"}`;
    let error = false;

    if (
        typeof oreTag !== "string" ||
        oreTag.trim() === "" ||
        !oreTag.includes(":")
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Scry Ritual: Invalid oreTag. \n` +
            "Expected a non-empty resource location (e.g., 'c:ores/aluminum')."
        );
        error = true;
    }

    let inputTag = {"tag": oreTag}

    if (!validateInputArsN(inputTag)){
        console.error(
            `[MustJS] [${diagnosticId}] Scry Ritual: Invalid oreTag. \n` +
            `Ore Tag: ${mustjsGetObjectIdArsN(oreTag)}\n`+
            "Expected a valid tag (e.g., 'c:ores/aluminum')."
        )
        error = true;
    }

    if (error) {
        return;
    }

    e.custom({
        type: "ars_nouveau:scry_ritual",
        augment: oreTag,
        highlight: oreTag
    }).id(
        mustjsUniqueRecipeIdArsN(
            `mustjs:${recipeType}/${oreTag.replace(":", "_")}`
        )
    );
}

/**
 * Creates or replaces an Ars Nouveau glyph recipe.
 *
 * Removes an existing glyph recipe with the same recipe ID,
 * then registers the new recipe using the output item's ID.
 *
 * @param {Object} e The KubeJS recipe event.
 * @param {Object} output The output item representing the glyph.
 *                          Use the helper function `itemOutput()` or `itemOutputStack()`.
 * @param {Array<Object>} input An array of ingredients required to craft the glyph.
 *                          Use helper functions such as `itemInput()` or `itemInputTag()`.
 *                          All items must be wrapped inside an array [].
 * @param {number} expCost The experience cost of the recipe.
 *
 * @example
 * glyph(
 *     e,
 *     itemOutput('ars_nouveau:glyph_underfoot'),
 *     [
 *         itemInput('minecraft:iron_boots'),
 *         itemInput('createmechanisms:source_mechanism')
 *     ],
 *     200
 * );
 */
function glyph(e, output, input, expCost) {
    const recipeType = "glyph";
    const diagnosticId = mustjsDiagnosticRecipeIdArsN(recipeType, output);
    let error = false;

    // Validate output
    if (!validateOutputArsN(output)) {
        console.error(
            `[MustJS] [${diagnosticId}] Glyph: Invalid output. \n` +
            `Item Output: ${mustjsGetObjectIdArsN(output)}\n`+
            "Expected a valid item output created with an item output helper."
        );
        error = true;
    }

    // Validate inputs
    if (!Array.isArray(input) || input.length === 0) {
        console.error(
            `[MustJS] [${diagnosticId}] Glyph: Invalid inputs. \n` +
            "Expected a non-empty array of valid item or item tag inputs."
        );
        error = true;
    }

    if (Array.isArray(input)) {
        for (let i = 0; i < input.length; i++) {
            if (
                !validateInputArsN(input[i]) ||
                typeof input[i].fluid === "string"
            ) {
                console.error(
                    `[MustJS] [${diagnosticId}] Glyph: Invalid input at index ${i}. \n` +
                    `Item Input ${i}: ${mustjsGetObjectIdArsN(input[i])}\n`+
                    "Expected a valid item or item tag input."
                );
                error = true;
            }
        }
    }

    // Validate experience cost
    if (
        typeof expCost !== "number" ||
        !Number.isFinite(expCost) ||
        expCost < 0
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Glyph: Invalid expCost. \n` +
            "Expected a non-negative, finite number."
        );
        error = true;
    }

    // Stop if any validation failed
    if (error) {
        return;
    }

    const recipeBase =
        `mustjs:${recipeType}/${output.id.replace(":", "_")}`;

    const recipeId = mustjsUniqueRecipeIdArsN(recipeBase);

    // Remove the existing glyph recipe
    e.remove({
        id: output.id,
        type: "ars_nouveau:glyph"
    });

    // Register the new glyph recipe
    e.custom({
        type: "ars_nouveau:glyph",
        exp: expCost,
        inputs: input,
        output: output
    }).id(recipeId);
}

/**
 * Creates or replaces an Ars Nouveau enchantment recipe.
 *
 * Removes an existing enchantment recipe with the specified enchantment ID,
 * then registers a new recipe with the given level, pedestal ingredients,
 * and Source cost.
 *
 * The enchantment argument can be a resource location string or an object
 * containing an `id` property.
 *
 * @param {Object} e The KubeJS recipe event.
 * @param {string|{id: string}} enchantment The enchantment ID or an object containing it.
 * @param {number} level The enchantment level to apply.
 * @param {Array<Object>} input An array of ingredients required on the pedestals.
 *                          Use helper functions such as `itemInput()` or `itemInputTag()`.
 *                          All items must be wrapped inside an array [].
 * @param {number} sourceCost The amount of Source consumed by the recipe.
 *
 * @example
 * ars_enchant(
 *     e,
 *     'minecraft:bane_of_arthropods',
 *     1,
 *     [
 *         itemInput('ars_nouveau:source_gem_block'),
 *         itemInput('minecraft:fermented_spider_eye')
 *     ],
 *     2000
 * );
 */
function ars_enchant(e, enchantment, level, input, sourceCost) {
    const recipeType = "enchantment";
    let enchantmentId = "unknown";
    let error = false;

    // Validate enchantment ID
    if (typeof enchantment === "string") {
        enchantmentId = enchantment;
    } else if (
        typeof enchantment === "object" &&
        enchantment !== null &&
        !Array.isArray(enchantment) &&
        typeof enchantment.id === "string"
    ) {
        enchantmentId = enchantment.id;
    }

    const diagnosticId = mustjsDiagnosticRecipeIdArsN(
        recipeType,
        { id: enchantmentId }
    );

    if (
        typeof enchantmentId !== "string" ||
        enchantmentId.trim() === "" ||
        !enchantmentId.includes(":") ||
        !validateEnchantmentArsN(enchantmentId)
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Ars Enchant: Invalid enchantment. \n` +
            `Enchantment ID: ${mustjsGetObjectIdArsN(enchantment)}\n`+
            "Expected a valid enchantment ID or an object containing a valid ID."
        );
        error = true;
    }

    // Validate level
    if (
        typeof level !== "number" ||
        !Number.isSafeInteger(level) ||
        level <= 0
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Ars Enchant: Invalid level. \n` +
            "Expected a positive safe integer."
        );
        error = true;
    }

    if (!Array.isArray(input) || input.length === 0) {
        console.error(
            `[MustJS] [${diagnosticId}] Ars Enchant: Invalid inputs. \n` +
            "Expected a non-empty array of valid item or item tag inputs."
        );
        error = true;
    } else {
        for (let i = 0; i < input.length; i++) {
            if (
                !validateInputArsN(input[i]) ||
                typeof input[i].fluid === "string"
            ) {
                console.error(
                    `[MustJS] [${diagnosticId}] Ars Enchant: Invalid input at index ${i}. \n` +
                    `Item Input ${i}: ${mustjsGetObjectIdArsN(input[i])}\n`+
                    "Expected a valid item or item tag input."
                );
                error = true;
            }
        }
    }

    // Validate source cost
    if (
        typeof sourceCost !== "number" ||
        !Number.isFinite(sourceCost) ||
        sourceCost <= 0
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Ars Enchant: Invalid sourceCost. \n` +
            "Expected a positive, finite source cost."
        );
        error = true;
    }

    if (error) {
        return;
    }

    // Remove existing enchantment recipe
    e.remove({
        id: enchantmentId,
        type: "ars_nouveau:enchantment"
    });

    const recipeBase = `mustjs:${recipeType}/${enchantment.replace(":", "_")}`;
    const recipeId = mustjsUniqueRecipeIdArsN(recipeBase);

    e.custom({
        type: "ars_nouveau:enchantment",
        enchantment: enchantmentId,
        level: level,
        pedestalItems: input,
        sourceCost: sourceCost
    }).id(recipeId);
}

/**
 * Creates a recipe for the Ars Nouveau Dispel Entity mechanic.
 *
 * Generates a recipe ID from the specified entity ID and associates
 * the recipe with the supplied loot conditions and loot table.
 *
 * The generated recipe ID follows this format:
 * `createmechanisms:dispel_<namespace>_<entity>`.
 *
 * The loot conditions and loot table must use the structure expected
 * by the Ars Nouveau Dispel Entity recipe serializer.
 *
 * @param {Object} e The KubeJS recipe event.
 * @param {string} entity The resource location of the entity affected by the recipe.
 * @param {Array<Object>} loot_conditions An array of conditions required for the loot.
 * @param {string} loot_table The resource location of the loot table used by the recipe.
 *
 * @example
 * dispel_entity(
 *     e,
 *     'minecraft:trader_llama',
 *     [
 *         {
 *             condition: 'minecraft:entity_properties',
 *             entity: 'this'
 *         }
 *     ],
 *     'createmechanisms:dispel_trader_llama'
 * );
 *
 * @remarks
 * Use LootJS to create and configure the loot tables that define the drops.
 */
function dispel_entity(e, entity, loot_conditions, loot_table) {
    const recipeType = "dispel_entity";

    const diagnosticId = mustjsDiagnosticRecipeIdArsN(
        recipeType,
        {
            id: typeof entity === "string" ? entity : "unknown"
        }
    );

    let error = false;

    // Validate entity ID.
    if (
        typeof entity !== "string" ||
        entity.trim() === "" ||
        !entity.includes(":") ||
        !entityExistsArsN(entity)
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Dispel Entity: Invalid entity. \n` +
            `Entity: ${entity}\n`+
            "Expected a valid entity ID (e.g., 'minecraft:zombie')."
        );
        error = true;
    }

    // Validate loot conditions.
    if (
        !Array.isArray(loot_conditions)
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Dispel Entity: Invalid loot_conditions. \n` +
            "Expected a non-empty array of loot conditions."
        );
        error = true;
    }

    // Validate loot table ID.
    if (
        typeof loot_table !== "string" ||
        loot_table.trim() === "" ||
        !loot_table.includes(":") ||
        !validateLootTableArsN(loot_table)
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Dispel Entity: Invalid loot_table. \n` +
            `Loot Table: ${loot_table}\n`+
            "Expected a valid loot table resource location."
        );
        error = true;
    }

    if (error) return;

    // Build the recipe ID.
    const recipeBase =
        `mustjs:${recipeType}/${entity.replace(":", "_")}`;

    const recipeId = mustjsUniqueRecipeIdArsN(recipeBase);

    // Register the recipe.
    e.custom({
        type: "ars_nouveau:dispel_entity",
        entity: entity,
        loot_conditions: loot_conditions,
        loot_table: loot_table
    }).id(recipeId);
}

/**
 * Creates an Ars Nouveau crushing recipe.
 *
 * Defines the input ingredient, output results, and whether block placement
 * should be skipped when the recipe is processed.
 *
 * The `place` parameter is assigned to `skip_block_place`.
 * If omitted or set to null, its default value is `false`.
 *
 * @param {Object} e The KubeJS recipe event.
 * @param {Object|Array<Object>} output The crushing result or an array of results.
 *                         Use the helper function `crushingOutput()`.
 * @param {Object} input The input ingredient used by the recipe.
 *                         Use the helper function `itemInput`
 * @param {boolean} [place=false] Whether to skip block placement during processing.
 *
 * @example
 * ars_crushing(
 *     e,
 *     [
 *         crushingOutput('ae2:certus_quartz_crystal', 1, 4, 1),
 *         crushingOutput('ae2:certus_quartz_dust', 0.2, 2, 2)
 *     ],
 *     itemInput('ae2:quartz_cluster')
 * );
 */
function ars_crushing(e, output, input, place) {
    const recipeType = "crush";

    const diagnosticOutput = output[0].stack.id

    const diagnosticId = mustjsDiagnosticRecipeIdArsN(
        recipeType,
        {id: diagnosticOutput}
    );

    let error = false;

    // Validate output array.
    if (!Array.isArray(output) || output.length === 0) {
        console.error(
            `[MustJS] [${diagnosticId}] Ars Crushing: Invalid output. \n` +
            "Expected a non-empty array of valid item outputs created with crushingOutput()."
        );
        error = true;
    } else {
        for (let i = 0; i < output.length; i++) {
            let currentOutput = output[i];

            if (
                currentOutput === null ||
                typeof currentOutput !== "object" ||
                currentOutput.stack === null ||
                typeof currentOutput.stack !== "object" ||
                typeof currentOutput.stack.id !== "string"
            ) {
                console.error(
                    `[MustJS] [${diagnosticId}] Ars Crushing: ` +
                    `Invalid output at index ${i}. \n` +
                    "Expected an output created with crushingOutput()."
                );
                error = true;
                continue;
            }

            if (!validateOutputArsN(output[i])) {
                console.error(
                    `[MustJS] [${diagnosticId}] Ars Crushing: \n` +
                    `Item Output ${i}: ${mustjsGetObjectIdArsN(output[i])}\n`+
                    "Expected a valid item output created with crushingOutput()."
                );

                error = true;
            }
        }
    }

    // Validate input.
    if (
        !validateInputArsN(input) ||
        (input !== null &&
            typeof input === "object" &&
            typeof input.fluid === "string")
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Ars Crushing: Invalid input. \n` +
            `Item input: ${mustjsGetObjectIdArsN(input)}\n`+
            "Expected a valid item or item tag input created with itemInput() or itemInputTag()."
        );

        error = true;
    }

    // Apply the default value.
    if (place === undefined || place === null) {
        place = false;
    }

    // Validate place.
    if (typeof place !== "boolean") {
        console.error(
            `[MustJS] [${diagnosticId}] Ars Crushing: Invalid place. \n` +
            `Current Place: ${place}` +
            "Expected a boolean value (true or false)."
        );

        error = true;
    }

    if (error){
        return
    }

    // Generate the recipe ID.
    const recipeBase =
        `mustjs:crush/${output[0].stack.id.replace(":", "_")}`;

    const recipeId = mustjsUniqueRecipeIdArsN(recipeBase);

    // Register the recipe.
    e.custom({
        type: "ars_nouveau:crush",
        input: input,
        output: output,
        skip_block_place: place
    }).id(recipeId);
}

/**
 * Creates a constant color object in the format used by Ars Nouveau.
 *
 * This helper only returns a color object; it does not register a recipe.
 *
 * The RGB components are passed directly to the returned object.
 * Use values appropriate for the color format expected by Ars Nouveau.
 *
 * @param {number} r The red component.
 * @param {number} g The green component.
 * @param {number} b The blue component.
 * @returns {{id: string, r: number, g: number, b: number}} The constant color object.
 *
 * @example
 * const color = rgb(255, 40, 20);
 */
function rgb(r, g, b) {
    return {
        id: "ars_nouveau:constant",
        r: r,
        g: g,
        b: b
    };
}

/**
 * Creates a custom Ars Nouveau Caster Tome recipe.
 *
 * Validates the supplied spell glyphs before registering the recipe.
 * Allows you to configure the tome's name, flavor text, spell,
 * sound family, color, pitch, and volume.
 *
 * The recipe ID follows this format:
 * `createmechanisms:tomes/<id>`.
 *
 * @param {Object} e The KubeJS recipe event.
 * @param {string} name The display name of the tome.
 * @param {string} id The identifier used in the recipe ID.
 * @param {string} flavourText The descriptive flavor text displayed for the tome.
 * @param {string[]} spell An array of glyph item IDs that define the spell.
 * @param {Object} color The tome's color object, preferably created with `rgb()`.
 *
 * @example
 * casterTome(
 *     e,
 *     'Danger Vault',
 *     'danger_vault',
 *     'Vault without all those safety precautions.',
 *     [
 *         'ars_nouveau:glyph_projectile',
 *         'ars_nouveau:glyph_crush'
 *     ],
 *     rgb(255, 0, 0)
 * );
 */
function casterTome(e, name, id, flavourText, spell, color) {
    const recipeType = "caster_tome";

    const diagnosticId = mustjsDiagnosticRecipeIdArsN(
        recipeType,
        {
            id: typeof id === "string" && id.trim() !== ""
                ? id
                : "unknown"
        }
    );

    let error = false;

    if (typeof name !== "string" || name.trim() === "") {
        console.error(
            `[MustJS] [${diagnosticId}] Caster Tome: Invalid name. \n` +
            "Expected a non-empty string."
        );
        error = true;
    }
    if (typeof id !== "string" || id.trim() === "" || !/^[a-z0-9_.-]+$/.test(id)) {
        console.error(
            `[MustJS] [${diagnosticId}] Caster Tome: Invalid id. \n` +
            "Expected a non-empty identifier containing only lowercase letters, numbers, underscores, periods, or hyphens."
        );
        error = true;
    }
    if (typeof flavourText !== "string" || flavourText.trim() === "") {
        console.error(
            `[MustJS] [${diagnosticId}] Caster Tome: Invalid flavourText. \n` +
            "Expected a non-empty string."
        );
        error = true;
    }
    if (!Array.isArray(spell) || spell.length === 0) {
        console.error(
            `[MustJS] [${diagnosticId}] casterTome: Invalid inputs. \n` +
            "Expected a non-empty array of item, item tag, or fluid inputs."
        );
        error = true;
    }
    else {
        for (let i = 0; i < spell.length; i++) {
            if (typeof spell[i] !== "string") {
                console.error(
                    `[MustJS] [${diagnosticId}] casterTome: Invalid spell. \n` +
                    `Expected a glyph item ID string, received: ${spell[i]}`
                );

                error = true;
                continue;
            }

            if (!spell[i].includes("ars_nouveau:glyph_")) {
                console.error(
                    `[MustJS] [${diagnosticId}] casterTome: Invalid spell. \n` +
                    `Spell: ${spell[i]}. \nExpected an Ars Nouveau glyph ID.`
                );

                error = true;
                continue;
            }

            if (!validateInputArsN({item: spell[i]})) {
                console.error(
                    `[MustJS] [${diagnosticId}] casterTome: Invalid spell. \n` +
                    `Spell: ${spell[i]}. \nItem does not exist or is invalid.`
                );

                error = true;
            }
        }
    }

    if (
        color === null ||
        typeof color !== "object" ||
        Array.isArray(color) ||
        color.id !== "ars_nouveau:constant" ||
        typeof color.r !== "number" ||
        !Number.isFinite(color.r) ||
        color.r < 0 ||
        color.r > 255 ||
        typeof color.g !== "number" ||
        !Number.isFinite(color.g) ||
        color.g < 0 ||
        color.g > 255 ||
        typeof color.b !== "number" ||
        !Number.isFinite(color.b) ||
        color.b < 0 ||
        color.b > 255
    ) {
        console.error(
            `[MustJS] [${diagnosticId}] Caster Tome: Invalid color. \n` +
            "Expected an RGB object with id 'ars_nouveau:constant' and numeric r, g, and b values between 0 and 255."
        );
        error = true;
    }

    if (error) {
        return
    }

    const recipeBase = `createmechanisms:tomes/${id}`;
    const recipeId = mustjsUniqueRecipeIdArsN(recipeBase);

    e.custom({
        type: "ars_nouveau:caster_tome",
        color: color,
        flavour_text: flavourText,
        name: name,
        sound: {
            family: "ars_nouveau:default",
            pitch: 1.0,
            volume: 1.0
        },
        spell: spell,
        tome_type: "ars_nouveau:caster_tome"
    }).id(recipeId);
}
